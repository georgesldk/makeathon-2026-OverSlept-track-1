import { test, expect } from '@playwright/test'

test('Carrots: source, botanical evidence, claims, research and graph expansion', async ({ page }) => {
  await page.goto('http://127.0.0.1:8443/')
  await page.getByRole('textbox', { name: 'Search historical or scientific names' }).fill('Carrots')
  await page.getByRole('button', { name: /Culpeper.*Carrots/ }).click()
  await expect(page.getByRole('heading', { name: 'Carrots', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Historical Record', exact: true }).click()
  await expect(page.getByText('Garden Carrots are so well known', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Identification', exact: true }).click()
  const tierHelp = page.getByRole('button', { name: 'About Meets identification criteria' })
  await tierHelp.hover()
  await expect(page.getByRole('tooltip')).toContainText('not a proven historical identification')
  await tierHelp.focus()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await page.getByRole('button', { name: /Daucus carota L/ }).click()
  await expect(page.getByText('Taxonomic resolutions', { exact: true })).toBeVisible()
  await expect(page.getByText('Evidence records', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Open source record ↗' }).first()).toHaveAttribute('href', /^https:\/\/www\.gbif\.org\/species\/[0-9]+$/)
  await page.getByRole('button', { name: 'Claims & Research', exact: true }).click()
  await page.getByRole('button', { name: /Promotes menstrual flow/ }).click()
  await expect(page.getByText('women’s courses', { exact: false }).first()).toBeVisible()
  const claimPanel = page.getByRole('region', { name: 'Historical claim details' })
  await expect(claimPanel.getByText('Menstruation', { exact: true }).first()).toBeVisible()
  await expect(claimPanel.getByText('D008598', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Studies and assessments' })).toBeVisible()
  await expect(page.locator('.study-list article').first()).toBeVisible()
  await page.getByRole('button', { name: 'Relationships', exact: true }).click()
  await expect(page.locator('.react-flow__node').first()).toBeVisible()
  await page.locator('.react-flow__node').filter({ hasText: 'Daucus carota L.' }).click()
  await page.getByRole('button', { name: 'Expand related evidence in graph' }).click()
  await expect(page.locator('.react-flow__node[data-id^="r:"]').first()).toBeVisible()
})

