test('Adder’s Tongue shows separate authority and source evidence cards', async ({ page }) => {
  await page.goto('http://127.0.0.1:8443/')
  await page.getByRole('textbox', { name: 'Search historical or scientific names' }).fill('Adder')
  await page.getByRole('button', { name: /Culpeper.*Adder’s Tongue/ }).click()
  await page.getByRole('button', { name: 'Identification', exact: true }).click()
  await page.getByRole('button', { name: /Ophioglossum vulgatum L/ }).click()
  const resolution = page.locator('.resolution-card')
  await expect(resolution.filter({ hasText: 'WFO' })).toContainText('wfo-0001109043')
  await expect(resolution.filter({ hasText: 'WCVP' })).toContainText('3142394')
  const checklistRecord = page.locator('.evidence-card').filter({ hasText: 'clb:316691:49XBM' })
  await expect(checklistRecord).toContainText('ChecklistBank')
  await expect(checklistRecord).toContainText("Adder's Tongue")
  await expect(checklistRecord).toContainText('col')
  await checklistRecord.getByRole('button', { name: 'About Evidence grade' }).hover()
  await expect(page.getByRole('tooltip')).toContainText('not proof of historical identity')
})
